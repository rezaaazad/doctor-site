import { sectionSeed, settingsSeed, menuSeed, projectSeed, serviceSeed, testimonialSeed, seoSeed } from "@/lib/seed-data";
import { asObject, asStringArray } from "@/lib/utils";
import type { SiteData } from "@/lib/site";

export function fallbackSite(): SiteData {
  return {
    degraded: true,
    settings: { ...settingsSeed, socials: { ...settingsSeed.socials } },
    menus: menuSeed.map((item, index) => ({
      id: `fallback-menu-${index}`,
      label: item.label,
      labelEn: item.labelEn ?? "",
      href: item.href,
      location: item.location,
      sortOrder: item.sortOrder ?? index,
      visible: item.visible ?? true,
    })),
    sections: sectionSeed.map((section, index) => ({
      id: `fallback-section-${index}`,
      key: section.key,
      page: section.page,
      label: section.label,
      sortOrder: section.sortOrder,
      visible: true,
      content: asObject(section.content),
    })),
    projects: projectSeed.map((project, index) => ({
      id: `fallback-project-${index}`,
      slug: project.slug,
      title: project.title,
      titleEn: project.titleEn ?? "",
      subtitle: project.subtitle ?? "",
      subtitleEn: project.subtitleEn ?? "",
      excerpt: project.excerpt,
      excerptEn: project.excerptEn ?? "",
      body: project.body,
      bodyEn: project.bodyEn ?? "",
      coverUrl: project.coverUrl ?? "",
      images: asStringArray(project.images),
      tags: asStringArray(project.tags),
      year: project.year ?? "",
      client: project.client ?? "",
      role: project.role ?? "",
      url: project.url ?? "",
      featured: project.featured ?? false,
      published: true,
      sortOrder: project.sortOrder ?? index,
      seoTitle: project.seoTitle ?? "",
      seoDescription: project.seoDescription ?? "",
    })),
    services: serviceSeed.map((service, index) => ({
      id: `fallback-service-${index}`,
      number: service.number,
      title: service.title,
      titleEn: service.titleEn ?? "",
      summary: service.summary,
      summaryEn: service.summaryEn ?? "",
      body: service.body,
      bodyEn: service.bodyEn ?? "",
      priceLabel: service.priceLabel ?? "",
      includes: asStringArray(service.includes),
      href: service.href ?? "/services",
      visible: true,
      sortOrder: service.sortOrder ?? index,
    })),
    packages: [],
    steps: [],
    stats: [],
    logos: [],
    faqs: [],
    posts: [],
    testimonials: testimonialSeed.map((quote, index) => ({
      id: `fallback-quote-${index}`,
      name: quote.name,
      role: quote.role,
      roleEn: quote.roleEn ?? "",
      quote: quote.quote,
      quoteEn: quote.quoteEn ?? "",
      visible: true,
      sortOrder: quote.sortOrder ?? index,
    })),
    seo: seoSeed.map((entry) => ({
      id: entry.id,
      path: entry.path,
      title: entry.title,
      description: entry.description,
      ogImage: entry.ogImage ?? "",
      keywords: entry.keywords ?? "",
    })),
  };
}
