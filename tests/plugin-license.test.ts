import { describe, expect, it } from "vitest";
import { licenseHost, nextExpiry } from "../lib/licenses/domain";
import { cartKey } from "../lib/store/addons";

describe("plugin license purchase", () => {
  it("preserves the WordPress host and encodes IDNs", () => {
    expect(licenseHost("https://WWW.Shop.Example.com/")).toBe(
      "www.shop.example.com",
    );
    expect(licenseHost("فروشگاه.example")).toBe(
      new URL("https://فروشگاه.example").hostname,
    );
    for (const value of [
      "localhost",
      "shop.test/path",
      "a@shop.test",
      "127.0.0.1",
      "example.com:80",
    ])
      expect(licenseHost(value)).toBe("");
  });
  it("keeps purchases for different hosts and renewals separate", () => {
    const key = (host: string, renewal = "") =>
      cartKey("product", "pro", [], host, renewal);
    expect(
      new Set([key("a.test"), key("b.test"), key("a.test", "old")]).size,
    ).toBe(3);
  });
  it("extends active validity and starts expired terms on the paid UTC day", () => {
    const paid = new Date("2028-02-28T18:26:12Z");
    expect(nextExpiry(paid, 2).toISOString()).toBe("2028-02-29T23:59:59.000Z");
    expect(nextExpiry(paid, 1, new Date("2027-01-01Z"))).toEqual(
      nextExpiry(paid, 1),
    );
    expect(nextExpiry(paid, 1, nextExpiry(paid, 2)).toISOString()).toBe(
      "2028-03-01T23:59:59.000Z",
    );
  });
});

it("reads the reference certificate generated by the Owner issuer", async () => {
  const { readFileSync } = await import("node:fs");
  const { verify } = await import("node:crypto");
  const folder = "tests/fixtures/plugin-license/";
  const cert = JSON.parse(readFileSync(folder + "license.json", "utf8"));
  const payload = Buffer.from(cert.payload, "base64");
  expect(
    verify(
      "RSA-SHA256",
      payload,
      readFileSync(folder + "public.pem"),
      Buffer.from(cert.signature, "base64"),
    ),
  ).toBe(true);
  expect(JSON.parse(payload.toString())).toEqual({
    tier: "starter",
    host: "shop.example.test",
    expires: 4102444799,
  });
});
